/** متن‌هایی که اپ به‌صورت تصادفی برای یادآوری استفاده می‌کند. */
export function nudgePrompts(partnerName: string): string[] {
  const p = partnerName?.trim() || 'نیمهٔ دیگرت';
  return [
    `الان وقت خوبیه به ${p} یه پیام عاشقانه بدی 💌`,
    `${p} رو غافلگیر کن؛ بهش بگو چقدر دوستش داری ❤️`,
    `یه لحظه گوشی رو بردار و حالِ ${p} رو بپرس 🌹`,
    `یه دلیل کوچیک برای لبخندِ ${p} بساز؛ یه پیام قشنگ بفرست.`,
    `یادت نره: ${p} از شنیدن «دوستت دارم» سیر نمی‌شه 🥰`,
  ];
}

export function randomNudge(partnerName: string): string {
  const list = nudgePrompts(partnerName);
  return list[Math.floor(Math.random() * list.length)];
}
